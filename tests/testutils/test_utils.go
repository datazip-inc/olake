// applySuite names the suite and rewires source.json where concurrent suites contend on a CDC
// reader; file isolation itself comes from every TestConfig owning a private working dir.
func applySuite(t *testing.T, c *TestConfig, suite string) {
	t.Helper()
	if suite == "" {
		return
	}
	c.Suite = suite
	if edit := variantSourceOverride(c); edit != nil {
		require.NoError(t, editJSONFile(c.HostSourcePath, edit),
			"failed to derive the source config for suite %q", suite)
	}
}

// copyJSONWithEdit reads the JSON at srcHost, applies edit, and writes the result to dstHost --
// used to derive a per-suite config from a shared base file without touching the base.
func copyJSONWithEdit(srcHost, dstHost string, edit func(map[string]interface{}) error) error {
	raw, err := os.ReadFile(srcHost)
	if err != nil {
		return fmt.Errorf("failed to read %s: %s", srcHost, err)
	}
	doc, err := parseJSONDoc(raw)
	if err != nil {
		return fmt.Errorf("failed to parse %s: %s", srcHost, err)
	}
	if err := edit(doc); err != nil {
		return err
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal %s: %s", dstHost, err)
	}
	return writeHostFile(dstHost, out)
}

// variantSourceOverride gives a suite its own CDC reader where concurrent ones contend: a postgres
// replication slot, a kafka consumer group, a whole mssql database. nil for drivers that can share
// source.json. Whatever it renames here, SuiteDatabase and the driver's own connection must match.
func variantSourceOverride(c *TestConfig) func(map[string]interface{}) error {
	switch c.Driver {
	case string(constants.MSSQL):
		// Table separation alone races: DROP/CREATE TABLE modify database-scoped shared metadata
		// (system catalog, cdc schema) even for separate tables, and the loser transaction fails
		// as the deadlock victim (error 1205) -- so each suite owns a whole database.
		return func(doc map[string]interface{}) error {
			base, ok := doc["database"].(string)
			if !ok {
				return fmt.Errorf("no database in source config")
			}
			doc["database"] = SuiteDatabase(base, c.Suite)
			return nil
		}
	case string(constants.Postgres):
		return func(doc map[string]interface{}) error {
			updateMethod, ok := doc["update_method"].(map[string]interface{})
			if !ok {
				return fmt.Errorf("no update_method object in source config")
			}
			updateMethod["replication_slot"] = TestTableName(c)
			return nil
		}
	case string(constants.Kafka):
		return func(doc map[string]interface{}) error {
			base, ok := doc["consumer_group_id"].(string)
			if !ok || base == "" {
				return fmt.Errorf("no consumer_group_id in source config")
			}
			doc["consumer_group_id"] = withSuite(base, c.Suite)
			return nil
		}
	}
	return nil
}

// TestTableName is the source table a suite drives. The suite suffix is what keeps concurrent
// suites off each other's table -- without it they race the same DROP/CREATE.
func TestTableName(c *TestConfig) string {
	name := Ternary(c.DataFormat == "",
		fmt.Sprintf("%s_test_table_olake", c.Driver),
		fmt.Sprintf("%s_%s_test_table_olake", c.Driver, c.DataFormat)).(string)
	return withSuite(name, c.Suite)
}

// withSuite names a suite's own copy of a shared resource (table, database, consumer group, namespace).
func withSuite(base, suite string) string {
	return Ternary(suite == "", base, fmt.Sprintf("%s_%s", base, suite)).(string)
}

// SuiteDatabase names the source database a suite owns, for drivers whose CDC is database-scoped.
// Both sides must agree: variantSourceOverride rewrites source.json for olake, and the driver's
// own ExecuteQuery connection calls this with the same suite.
func SuiteDatabase(base, suite string) string {
	return withSuite(base, suite)
}

// destinationDBPrefix is passed as --destination-database-prefix. It carries the suite because
// Iceberg.Check probes <prefix>_test_olake on every sync, and suites would race that CREATE TABLE.
func destinationDBPrefix(c *TestConfig) string {
	prefix := Ternary(c.DataFormat == "",
		fmt.Sprintf("integration_%s", c.Driver),
		fmt.Sprintf("integration_%s_%s", c.Driver, c.DataFormat)).(string)
	return withSuite(prefix, c.Suite)
}

// verifyDiscoveredStreams asserts the discovered catalog holds exactly the streams test_streams.json
func verifyDiscoveredStreams(t *testing.T, expectedPath, actualPath string) {
	t.Helper()

	load := func(path, what string) map[string]interface{} {
		data, err := os.ReadFile(path)
		require.NoError(t, err, "failed to read %s streams JSON (%s)", what, path)
		var doc map[string]interface{}
		require.NoError(t, json.Unmarshal(data, &doc), "failed to parse %s streams JSON (%s)", what, path)
		return doc
	}
	expected := load(expectedPath, "expected")
	actual := load(actualPath, "discovered")

	// streams[]: keyed by namespace.name, which is what makes a stream unique in a catalog.
	indexStreams := func(doc map[string]interface{}) map[string]interface{} {
		out := map[string]interface{}{}
		entries, _ := doc["streams"].([]interface{})
		for _, raw := range entries {
			wrapper, ok := raw.(map[string]interface{})
			if !ok {
				continue
			}
			stream, ok := wrapper["stream"].(map[string]interface{})
			if !ok {
				continue
			}
			out[fmt.Sprintf("%v.%v", stream["namespace"], stream["name"])] = wrapper
		}
		return out
	}
	// selected_streams: a map of namespace -> []{stream_name, ...}; key the same way.
	indexSelected := func(doc map[string]interface{}) map[string]interface{} {
		out := map[string]interface{}{}
		byNamespace, _ := doc["selected_streams"].(map[string]interface{})
		for namespace, raw := range byNamespace {
			entries, _ := raw.([]interface{})
			for _, entry := range entries {
				selected, ok := entry.(map[string]interface{})
				if !ok {
					continue
				}
				out[fmt.Sprintf("%v.%v", namespace, selected["stream_name"])] = selected
			}
		}
		return out
	}

	compare := func(section string, want, got map[string]interface{}) {
		require.Equal(t, slices.Sorted(maps.Keys(want)), slices.Sorted(maps.Keys(got)),
			"%s: discover returned a different set of streams than test_streams.json", section)
		for key, wantEntry := range want {
			wantJSON, err := json.Marshal(wantEntry)
			require.NoError(t, err)
			gotJSON, err := json.Marshal(got[key])
			require.NoError(t, err)
			require.Truef(t, NormalizedEqual(string(wantJSON), string(gotJSON)),
				"%s: discovered %q does not match test_streams.json\nExpected:\n%s\nGot:\n%s", section, key, wantJSON, gotJSON)
		}
	}
	compare("streams", indexStreams(expected), indexStreams(actual))
	compare("selected_streams", indexSelected(expected), indexSelected(actual))

	t.Logf("Generated streams validated with test streams")
}

// seedCatalogFromTestStreams writes test_streams.json out as the suite's catalog, retargeting it at
// the suite's table and namespace. Field-by-field: stream names carry the source's casing, tables
// the destination's, so one text substitution would rename only one of them.
func seedCatalogFromTestStreams(t *testing.T, c *TestConfig, testTable string) {
	t.Helper()
	if c.Suite == "" {
		data, err := os.ReadFile(c.HostTestCatalogPath)
		require.NoError(t, err, "failed to read test_streams.json")
		require.NoError(t, writeHostFile(c.HostCatalogPath, data), "failed to write %s", c.HostCatalogPath)
		return
	}

	base := strings.TrimSuffix(testTable, "_"+c.Suite)
	fromStream, toStream := normalizeStreamName(c.Driver, base), normalizeStreamName(c.Driver, testTable)

	require.NoError(t, copyJSONWithEdit(c.HostTestCatalogPath, c.HostCatalogPath, func(doc map[string]interface{}) error {
		entries, _ := doc["streams"].([]interface{})
		for _, raw := range entries {
			wrapper, ok := raw.(map[string]interface{})
			if !ok {
				continue
			}
			stream, ok := wrapper["stream"].(map[string]interface{})
			if !ok {
				continue
			}
			if stream["name"] == fromStream {
				stream["name"] = toStream
			}
			if stream["destination_table"] == base {
				stream["destination_table"] = testTable
			}
			// A baked destination_database is used verbatim (it overrides the prefix flag), so suffix
			// it or concurrent suites race the CREATE on one shared namespace.
			if ddb, ok := stream["destination_database"].(string); ok && ddb != "" {
				stream["destination_database"] = withSuite(ddb, c.Suite)
			}
		}
		byNamespace, _ := doc["selected_streams"].(map[string]interface{})
		for _, raw := range byNamespace {
			selected, _ := raw.([]interface{})
			for _, entry := range selected {
				stream, ok := entry.(map[string]interface{})
				if !ok {
					continue
				}
				if stream["stream_name"] == fromStream {
					stream["stream_name"] = toStream
				}
			}
		}
		return nil
	}), "failed to seed the %q catalog", c.Suite)
}

