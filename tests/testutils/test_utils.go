// history stores the RPS values and the last updated time for a given mode.
type history struct {
	RPS       []float64 `json:"rps"`
	UpdatedAt time.Time `json:"updated_at"`
}

// benchmarkStore stores the benchmark RPS history for backfill and CDC modes.
type benchmarkStore struct {
	Backfill history `json:"backfill"`
	CDC      history `json:"cdc"`
	FilePath string  `json:"-"`
}

// initializes the benchmark store with the given path and loads the stored benchmarks data from the file.
func loadBenchmarks(path string) (*benchmarkStore, error) {
	store := &benchmarkStore{
		Backfill: history{
			RPS:       make([]float64, 0, maxRPSHistorySize),
			UpdatedAt: time.Now().UTC(),
		},
		CDC: history{
			RPS:       make([]float64, 0, maxRPSHistorySize),
			UpdatedAt: time.Now().UTC(),
		},
		FilePath: path,
	}
	if err := store.load(); err != nil {
		return nil, err
	}
	return store, nil
}

// load loads the stored benchmarks data from the file.
func (s *benchmarkStore) load() error {
	if err := UnmarshalFile(s.FilePath, s, false); err != nil {
		if _, statErr := os.Stat(s.FilePath); os.IsNotExist(statErr) {
			// Missing file is acceptable, it will be created when the first RPS is recorded.
			return nil
		}
		return fmt.Errorf("failed to load rps benchmarks from file %s: %s", s.FilePath, err)
	}

	return nil
}

// record records a new benchmark RPS value for the given driver and mode, and persists it to the file.
func (s *benchmarkStore) record(
	isBackfill bool,
	rps float64,
) error {
	rpsValues := Ternary(
		isBackfill,
		s.Backfill.RPS,
		s.CDC.RPS,
	).([]float64)

	rpsValues = append(rpsValues, rps)

	// Truncate history to maintain a rolling window of the last maxRPSHistorySize values.
	if len(rpsValues) > maxRPSHistorySize {
		rpsValues = rpsValues[1:]
	}

	if isBackfill {
		s.Backfill.RPS = rpsValues
		s.Backfill.UpdatedAt = time.Now().UTC()
	} else {
		s.CDC.RPS = rpsValues
		s.CDC.UpdatedAt = time.Now().UTC()
	}

	return FileLoggerWithPath(s, s.FilePath)
}

// stats returns the average RPS and count of past RPS values for the given driver and mode.
// The count cannot exceed maxRPSHistorySize.
func (s *benchmarkStore) stats(
	isBackfill bool,
) (averageRPS float64, observations int) {
	rpsValues := Ternary(
		isBackfill,
		s.Backfill.RPS,
		s.CDC.RPS,
	).([]float64)

	if len(rpsValues) == 0 {
		// No benchmarks recorded for this mode yet.
		return 0, 0
	}

	return Average(rpsValues), len(rpsValues)
}

// driverOrCommonConfig returns the driver's own fixture for file when present, else the shared
// one under tests/testdata; source.json never falls back.
func driverOrCommonConfig(fixturesPath, testsDir, file string) string {
	p := filepath.Join(fixturesPath, file)
	if file == "source.json" {
		return p
	}
	if _, err := os.Stat(p); os.IsNotExist(err) {
		return filepath.Join(testsDir, "..", "testdata", file)
	}
	return p
}

// GetTestConfig returns the test config for a driver, called from a test in tests/<driver>.
// extraParams[0] optionally selects a testdata sub-directory (kafka's "json"/"avro" formats).
func GetTestConfig(t *testing.T, driver string, extraParams ...string) *TestConfig {
	t.Helper()
	// pwd is olake/tests/(driver)
	pwd, err := os.Getwd()
	require.NoError(t, err, "failed to determine the test directory")
	// root path is olake's root path
	rootPath := filepath.Join(pwd, "../..")
	dataFormat := ""
	if len(extraParams) > 0 {
		dataFormat = extraParams[0]
	}
	// Every config owns a fresh /tmp working dir seeded from the committed testdata, so the repo
	// files are read-only fixtures and concurrent suites never share a writable file
	fixturesPath := filepath.Join(pwd, "testdata", dataFormat)
	workDir, err := os.MkdirTemp("/tmp", fmt.Sprintf("olake-it-%s-", driver))
	require.NoError(t, err, "failed to create the test working directory")
	// Removed once the test passes, kept on failure for inspection. Logged, not fatal
	t.Cleanup(func() {
		if !t.Failed() {
			if err := os.RemoveAll(workDir); err != nil {
				t.Logf("failed to remove the test working directory %s: %s", workDir, err)
			}
		}
	})
	fixturePath := func(file string) string { return filepath.Join(fixturesPath, file) }
	hostPath := func(file string) string { return filepath.Join(workDir, file) }
	containerPath := func(file string) string { return path.Join(containerTestDataDir, file) }
	for _, file := range []string{"source.json", "iceberg_destination.json", "parquet_destination.json"} {
		require.NoError(t, copyFile(driverOrCommonConfig(fixturesPath, pwd, file), hostPath(file)), "failed to seed the test working directory")
	}
	// The arrow writer variant is derived, never committed: the base config stays the single
	// source of truth, and writer variants become a pure file choice (see testIcebergWriter).
	require.NoError(t, copyJSONWithEdit(hostPath("iceberg_destination.json"), hostPath("iceberg_destination_arrow.json"),
		func(doc map[string]interface{}) error {
			writer, ok := doc["writer"].(map[string]interface{})
			if !ok {
				return fmt.Errorf("no writer object in iceberg_destination.json")
			}
			writer["arrow_writes"] = true
			return nil
		}), "failed to derive the arrow destination config")
	return &TestConfig{
		Driver:                   driver,
		DataFormat:               dataFormat,
		HostRootPath:             rootPath,
		HostTestDataPath:         workDir,
		HostTestCatalogPath:      fixturePath("test_streams.json"),
		HostCatalogPath:          hostPath("streams.json"),
		HostStatePath:            hostPath("state.json"),
		HostStateCheckpointPath:  hostPath("state_checkpoint.json"),
		HostPerformanceStatePath: fixturePath("performance_state.json"),
		HostSourcePath:           hostPath("source.json"),
		HostStatsPath:            hostPath("stats.json"),
		BenchmarksPath:           fixturePath("benchmarks.json"),
		SourcePath:               containerPath("source.json"),
		CatalogPath:              containerPath("streams.json"),
		IcebergDestinationPath:   containerPath("iceberg_destination.json"),
		ParquetDestinationPath:   containerPath("parquet_destination.json"),
		StatePath:                containerPath("state.json"),
	}
}

// The helpers below edit the driver's config/catalog files on the host; the container sees the
// changes through the /testdata mount.

// parseJSONDoc decodes a JSON object keeping numbers as json.Number, so values the edit does not
// touch round-trip as their original literals instead of through float64 (which corrupts int64s
// beyond 2^53 and renders large values in scientific notation).
func parseJSONDoc(raw []byte) (map[string]interface{}, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var doc map[string]interface{}
	return doc, dec.Decode(&doc)
}

// editJSONFile reads path, applies edit to the decoded document, and writes it back.
func editJSONFile(path string, edit func(doc map[string]interface{}) error) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("failed to read %s: %s", path, err)
	}
	doc, err := parseJSONDoc(raw)
	if err != nil {
		return fmt.Errorf("failed to parse %s: %s", path, err)
	}
	if err := edit(doc); err != nil {
		return err
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal %s: %s", path, err)
	}
	return writeHostFile(path, out)
}

// writeHostFile writes to the shared /testdata mount, unlinking first: the container runs as root,
// so on Linux CI the test user cannot truncate a file a previous run left behind, only replace it.
func writeHostFile(path string, data []byte) error {
	_ = os.Remove(path)
	return os.WriteFile(path, data, 0600)
}

// normalizeStreamName uppercases the stream name for drivers whose catalogs store
// uppercase identifiers (e.g. Oracle).
func normalizeStreamName(driver, streamName string) string {
	return Ternary(slices.Contains(constants.UppercaseStreamDrivers, constants.DriverType(driver)), strings.ToUpper(streamName), streamName).(string)
}

// updateSelectedStreams rewrites selected_streams so only the given streams stay selected, with
// normalization enabled and the partition regex, filter config and excluded column applied.
func updateSelectedStreams(config *TestConfig, namespace, partitionRegex, filterConfig string, streams []string, columnToExclude string) error {
	if len(streams) == 0 {
		return nil
	}
	selectedNames := make(map[string]bool, len(streams))
	for _, s := range streams {
		selectedNames[normalizeStreamName(config.Driver, s)] = true
	}

	var filter interface{} = map[string]interface{}{}
	if filterConfig != "" {
		if err := json.Unmarshal([]byte(filterConfig), &filter); err != nil {
			return fmt.Errorf("failed to parse filter config: %s", err)
		}
	}

	return editJSONFile(config.HostCatalogPath, func(doc map[string]interface{}) error {
		selected, _ := doc["selected_streams"].(map[string]interface{})
		nsStreams, _ := selected[namespace].([]interface{})
		kept := make([]interface{}, 0, len(nsStreams))
		for _, raw := range nsStreams {
			stream, ok := raw.(map[string]interface{})
			if !ok || !selectedNames[fmt.Sprint(stream["stream_name"])] {
				continue
			}
			stream["normalization"] = true
			stream["partition_regex"] = partitionRegex
			stream["filter_config"] = filter
			if columnToExclude != "" {
				if selectedColumns, ok := stream["selected_columns"].(map[string]interface{}); ok {
					if columns, ok := selectedColumns["columns"].([]interface{}); ok {
						remaining := make([]interface{}, 0, len(columns))
						for _, col := range columns {
							if fmt.Sprint(col) != columnToExclude {
								remaining = append(remaining, col)
							}
						}
						selectedColumns["columns"] = remaining
					}
				}
			}
			kept = append(kept, stream)
		}
		doc["selected_streams"] = map[string]interface{}{namespace: kept}
		return nil
	})
}

// updateStreamConfig sets sync_mode and cursor_field on the stream identified by
// namespace+name in streams[].
func updateStreamConfig(config *TestConfig, namespace, streamName, syncMode, cursorField string) error {
	// in case of Oracle, the stream names are in uppercase in stream.json
	streamName = normalizeStreamName(config.Driver, streamName)
	return editJSONFile(config.HostCatalogPath, func(doc map[string]interface{}) error {
		streams, _ := doc["streams"].([]interface{})
		for _, raw := range streams {
			wrapper, ok := raw.(map[string]interface{})
			if !ok {
				continue
			}
			stream, ok := wrapper["stream"].(map[string]interface{})
			if !ok {
				continue
			}
			if stream["namespace"] == namespace && stream["name"] == streamName {
				stream["sync_mode"] = syncMode
				stream["cursor_field"] = cursorField
			}
		}
		return nil
	})
}

// resetStateFile clears state.json so incremental can perform its initial load
// (equivalent to a full load on first run), irrespective of any previous CDC run.
func resetStateFile(config *TestConfig) error {
	return writeHostFile(config.HostStatePath, fmt.Appendf(nil, `{"version": %d}`, constants.LatestStateVersion))
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return fmt.Errorf("failed to read %s: %s", src, err)
	}
	return writeHostFile(dst, data)
}

